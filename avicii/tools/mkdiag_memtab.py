#!/usr/bin/env python3
"""Emit avicii/shim/memtab.h: the compile-time memory table the diag ladder's
stage 5 (memory-map self-check) compares the live /memory node against.

The point is that the table is not a copy - it is read out of
tools/mkadt_avicii.py at build time, so the shim can never check against
numbers the ADT generator has since changed. If mkadt_avicii.py moves, stage 5
starts printing mismatches, which is exactly what it is for.

Covers:
  * the qemu/fallback dram window (DEFAULT_PHYS_BASE + DEFAULT_MEM_SIZE)
  * the plausibility floor (MIN_MEM_SIZE) and the panic-log carve
    (PANIC_LOG_SIZE, taken off the top of dram)
  * every fixed carve-out the /memory node must not claim: the GIC, the UFS
    host and the cont_splash_region framebuffer
  * the 4 GiB line the panic-log/pmap code assumes it can stay above

Usage: mkdiag_memtab.py [-o OUT.h] [--check]
  default OUT: avicii/shim/memtab.h (relative to the repository root)
  --check: write nothing, exit 1 if the checked-in header is stale.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

DEFAULT_OUT = os.path.join(ROOT, 'avicii', 'shim', 'memtab.h')

# (macro suffix, attribute on mkadt_avicii, what it is)
FIELDS = [
    ('DEFAULT_PHYS_BASE', 'DEFAULT_PHYS_BASE', 'fallback dram base'),
    ('DEFAULT_MEM_SIZE', 'DEFAULT_MEM_SIZE', 'fallback dram size'),
    ('MIN_MEM_SIZE', 'MIN_MEM_SIZE', 'smallest believable dram extent'),
    ('PANIC_LOG_SIZE', 'PANIC_LOG_SIZE', 'panic log carved off the top'),
    ('GICD', 'GICD', 'GIC distributor'),
    ('GICD_SIZE', 'GICD_SIZE', ''),
    ('GICR', 'GICR', 'GIC redistributor'),
    ('GICR_SIZE', 'GICR_SIZE', ''),
    ('FB', 'FB', 'cont_splash_region'),
    ('FB_SIZE', 'FB_SIZE', ''),
    ('UFS', 'UFS', 'ufshc'),
    ('UFS_SIZE', 'UFS_SIZE', ''),
    ('SOC_BASE', 'SOC_BASE', ''),
]
# Carve-outs that must never be inside a /memory extent: (base, size, name)
CARVEOUTS = [('GICD', 'GICD_SIZE', 'g'), ('GICR', 'GICR_SIZE', 'r'),
             ('FB', 'FB_SIZE', 's'), ('UFS', 'UFS_SIZE', 'u')]

HEADER = '''/* Generated by avicii/tools/mkdiag_memtab.py - do not edit.
 *
 * Values read out of avicii/tools/mkadt_avicii.py at build time; see that file
 * for the dts citations. diag.c stage 5 compares the live /memory node against
 * them and prints every mismatch instead of panicking.
 *
 * source   : avicii/tools/mkadt_avicii.py
 * sha256   : %(sha)s
 */
#pragma once

#define MT_SRC_SHA256 "%(sha)s"
#define MT_4G        0x100000000UL
'''


def render(mod):
    sha = hashlib.sha256(open(os.path.join(HERE, 'mkadt_avicii.py'), 'rb').read()).hexdigest()
    out = [HEADER % {'sha': sha}]
    for macro, attr, what in FIELDS:
        val = getattr(mod, attr)
        if not isinstance(val, int):
            raise SystemExit(f'{attr}: not an int ({val!r})')
        if what:
            out.append(f'#define MT_{macro} {val:#x}UL\t/* {what} */')
        else:
            out.append(f'#define MT_{macro} {val:#x}UL')
    out.append('')
    out.append('/* {base, size, tag} extents that must not overlap dram. The tag is a')
    out.append(' * plain char so the table carries no pointers: an array of string')
    out.append(' * pointers would need ABS64 relocations the unpinned image cannot use. */')
    out.append('struct mt_carveout { unsigned long base, size; char tag; };')
    words = ', '.join('{ MT_%s, MT_%s, \'%s\' }' % (b, s, t) for b, s, t in CARVEOUTS)
    out.append(f'#define MT_CARVEOUTS {words}')
    out.append('#define MT_N_CARVEOUTS %d' % len(CARVEOUTS))
    out.append('')
    return '\n'.join(out)


def main(argv):
    out = DEFAULT_OUT
    if '-o' in argv:
        out = argv[argv.index('-o') + 1]
    check = '--check' in argv

    import mkadt_avicii  # noqa: E402  (needs sys.path above)
    text = render(mkadt_avicii)

    if check:
        try:
            cur = open(out).read()
        except OSError:
            cur = None
        if cur != text:
            print(f'{out}: stale, run {os.path.basename(__file__)}', file=sys.stderr)
            return 1
        print(f'{out}: up to date')
        return 0

    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    open(out, 'w').write(text)
    print(f'{out}: {len(text)} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
