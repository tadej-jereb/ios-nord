#!/usr/bin/env python3
"""E §§2/4 offmap + QC calls -> typed context-first dispatch adapters.

Signatures come from the Khronos registry in Mesa, never Apple headers/code.
Exported or generated-proc-table Mesa names are classified direct; required/special
entries are wrap. Runtime resolution always tries OSMesaGetProcAddress first.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
DATA = REPO / 'docs/gpu-research/data'
MESA = REPO / 'build/gpu/mesa-build/src/gallium/targets/osmesa/libOSMesa.8.dylib'
# Missing offmap lines, explicitly named by E §4 (not inferred from adjacency).
REPAIRS = {0x1c8: 'glCopyTexSubImage2D', 0x970: 'glTexImage2D',
           0x9a0: 'glTexSubImage2D', 0xbe8: 'glCompressedTexImage2D',
           0x2008: 'glFramebufferParameteriAPPLE'}
SPECIAL = {'glGetString', 'glFinishObjectAPPLE', 'glFramebufferParameteriAPPLE',
           'glLabelObjectEXT', 'glInsertEventMarkerEXT', 'glPushGroupMarkerEXT',
           'glPopGroupMarkerEXT', 'glDeleteProgram'}
APPLE_FENCES = {'glGenFencesAPPLE', 'glDeleteFencesAPPLE', 'glSetFenceAPPLE',
                'glIsFenceAPPLE', 'glTestFenceAPPLE', 'glFinishFenceAPPLE', 'glTestObjectAPPLE'}
SPECIAL |= APPLE_FENCES

def offsets():
    qc = {int(x, 16) for x in json.loads((DATA / 'eagl-slots.json').read_text())}
    slots = {}
    for line in (DATA / 'eagl-offmap.txt').read_text().splitlines():
        fields = line.split()
        off = int(fields[0], 16)
        names = [x.removeprefix('_') for x in fields[1:]]
        if off == 0xd0:
            assert len(names) > 100
            continue  # full export list, NOT a dispatch mapping
        # This name contaminates several unrelated lines; retain unique lines
        # as UNVERIFIED stubs, but prefer the real named alias when present.
        clean = [x for x in names if x != 'glGetFramebufferParameteriAPPLE']
        slots[off] = clean[0] if clean else names[0]
    slots.update(REPAIRS)
    assert qc <= slots.keys() and len(qc) == 58
    return slots, qc

def generate():
    slots, qc = offsets()
    registry = ET.parse(REPO / 'build/gpu/mesa-src/src/mapi/glapi/registry/gl.xml')
    commands = {}
    for cmd in registry.findall('./commands/command'):
        proto = cmd.find('proto')
        name = proto.findtext('name')
        ret = ''.join(proto.itertext()).removesuffix(name).strip()
        types = []
        for param in cmd.findall('param'):
            raw = ''.join(param.itertext())
            pname = param.findtext('name')
            types.append(raw[:raw.rfind(pname)].strip())
        commands[name] = ret, types
    exports = set(re.findall(r'\b_(gl\w+)\b', subprocess.check_output(
        [str(REPO / 'tooling/opt/llvm/bin/llvm-nm'), '-gU', str(MESA)], text=True)))
    proc_table = (REPO / 'build/gpu/mesa-build/src/mapi/shared-glapi/glapi_mapi_tmp.h').read_text()
    proc_names = {'gl' + n for n in re.findall(r'"(\w+)\\0"', proc_table)}
    available = exports | proc_names
    h = ['/* Generated by gen_slots.py; offsets: E §§2/4, data/eagl-offmap.txt. */',
         '#ifndef SWEET_SLOTS_H', '#define SWEET_SLOTS_H', '#include "abi.h"',
         'struct sweet_context;',
         'struct sweet_slot { unsigned offset; const char *name, *kind; int called_by_qc; void *entry; };',
         'extern const struct sweet_slot sweet_slots[];',
         'extern const size_t sweet_slot_count;',
         'int sweet_slots_init(void);', 'void sweet_slots_fill(void **);']
    c = ['/* Generated; offsets from data/eagl-offmap.txt and E §4 repairs.',
         ' * GL signatures: Mesa Khronos registry (Apache-2.0).',
         ' * Every entry is a context-first adapter, including kind=direct. */',
         '#include "internal.h"', '#include "slots.h"']
    rows, init = [], []
    for off, name in sorted(slots.items()):
        special = name in SPECIAL
        typed = name in commands and (name in available or off in qc or name == 'glGetString')
        kind = 'wrap' if special or off in qc else ('direct' if typed else 'stub')
        fn = f'slot_{off:04x}'
        h.append(f'#define SLOT_{name}_{off:04x} {off:#06x} /* offmap / E §4 */')
        if name == 'glFramebufferParameteriAPPLE':
            ret, types = 'void', ['GLenum', 'GLenum', 'GLint *']
        elif name == 'glFinishObjectAPPLE':
            ret, types = 'void', ['GLenum', 'GLuint']
        elif name in commands:
            ret, types = commands[name]
        else:
            ret, types = 'uintptr_t', []
        decl = ', '.join(f'{t} a{i}' for i, t in enumerate(types))
        args = ', '.join(f'a{i}' for i in range(len(types)))
        typedef = ', '.join(types) or 'void'
        default = 'return;' if ret == 'void' else 'return 0;'
        c.append(f'/* E §4 / offmap {off:#06x}: {name} */')
        if typed and not special:
            c.append(f'static {ret} (*p_{fn})({typedef});')
            init.append(f'    p_{fn} = ({ret} (*)({typedef}))sweet_proc("{name}");')
            if off in qc and name != 'glAlphaFunc':
                init.append(f'    if (!p_{fn}) good = 0;')
        c.append(f'static {ret} {fn}(void *opaque{", " if decl else ""}{decl}) {{')
        c.append('    struct sweet_context *e = opaque;')
        c.append(f'    if (!sweet_enter(e, {off})) {{ {default} }}')
        if name == 'glGetString':
            c.append('    return sweet_string(e, a0);')
        elif name == 'glFinishObjectAPPLE':
            c.append('    (void)a0; (void)a1; sweet_finish(e); sweet_frame_mark(e, 0xeb8);')
        elif name == 'glFramebufferParameteriAPPLE':
            c.append('    (void)a0; if (a1 == 0x8A79 && a2) *a2 = 0; /* E §§4/10 */')
        elif name in APPLE_FENCES:
            c.append(f'    {"return " if ret != "void" else ""}sweet_{name}(e, {args});')
        elif name == 'glDeleteProgram':
            c.append('    sweet_delete_program(a0); /* shared shader/program slot, offmap */')
        elif special:
            c.extend(f'    (void)a{i};' for i in range(len(types)))
        elif typed:
            c.append(f'    if (!p_{fn}) {{ sweet_missing({off}); {default} }}')
            if (name.startswith('glDraw') and name != 'glDrawBuffers') or name in ('glClear', 'glClearBufferiv', 'glClearBufferuiv', 'glClearBufferfv', 'glClearBufferfi'):
                c.append('    sweet_before_draw(e);')
            if name == 'glDeleteTextures':
                c.append('    sweet_delete_textures(e, a0, a1);')
            if name == 'glTexImage2D':
                c.append('    if (a2 == GL_BGRA) a2 = GL_RGBA8; /* E §4 Apple internal format */')
            c.append(f'    {"return " if ret != "void" else ""}p_{fn}({args});')
            if name in ('glFinish', 'glFlush'):
                c.append('    sweet_writeback(e);')
            if name in ('glFinish', 'glFlush', 'glFenceSync', 'glClientWaitSync'):
                c.append(f'    sweet_frame_mark(e, {off});')
        else:
            c.extend(f'    (void)a{i};' for i in range(len(types)))
            c.append(f'    sweet_missing({off}); {default}')
        c.append('}')
        rows.append(f'    {{{off:#06x}, "{name}", "{kind}", {int(off in qc)}, (void *){fn}}},')
    c += ['const struct sweet_slot sweet_slots[] = {', *rows, '};',
          'const size_t sweet_slot_count = sizeof(sweet_slots) / sizeof(sweet_slots[0]);',
          'int sweet_slots_init(void) {', '    int good = 1;', *init, '    return good;', '}',
          'static uintptr_t unknown_slot(void *ctx) { (void)ctx; sweet_missing(0); return 0; }',
          'void sweet_slots_fill(void **table) {',
          '    for (size_t i = 2; i < SWEET_TABLE_SIZE / sizeof(void *); ++i)',
          '        table[i] = (void *)unknown_slot;',
          '    for (size_t i = 0; i < sweet_slot_count; ++i)',
          '        table[sweet_slots[i].offset / sizeof(void *)] = sweet_slots[i].entry;', '}']
    h += ['#define SWEET_SLOT_OFFSETS { ' + ', '.join(hex(x) for x in sorted(slots)) + ' }', '#endif']
    return {'slots.h': '\n'.join(h) + '\n', 'slots.c': '\n'.join(c) + '\n'}

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    opt = parser.parse_args()
    for name, data in generate().items():
        if opt.check:
            assert (HERE / name).read_text() == data, f'{name} is stale'
        else:
            (HERE / name).write_text(data)
    print('PASS generator: 0x00d0 is the full export list, excluded; E §4 repairs applied')
